def build_records():
    records = []
    for module, data in MODULES.items():
        for index, (concept, summary, review_prompt) in enumerate(data["concepts"], start=1):
            records.append({
                "id": f"d5-{module}-{index:02d}",
                "module": module,
                "version": "6.2.x",
                "title": f"{data['label']}: {concept}",
                "summary": (
                    f"{summary} Review focus: {review_prompt}. "
                    "Confirm the stated behavior against the cited official documentation and target Spring version "
                    "before approving this entry."
                ),
                "source_url": data["url"],
                "review": {
                    "status": "PENDING",
                    "reviewer": None,
                    "accuracy_score": None,
                    "notes": "Human verification required; not approved for production retrieval.",
                },
            })
    return records


def main():
    output = Path(__file__).resolve().parents[2] / "src/main/resources/knowledge/d5-review-seed.json"
    records = build_records()
    if len(records) < 150 or len({record["id"] for record in records}) != len(records):
        raise SystemExit("D5 seed must contain at least 150 records with unique IDs")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(records)} pending-review records to {output}")


if __name__ == "__main__":
    main()
